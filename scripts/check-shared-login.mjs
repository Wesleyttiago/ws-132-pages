import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { resolve } from "node:path";
import { makeApp } from "../standalone-dist/server/runtime.mjs";
const chunks=[];for await(const chunk of process.stdin)chunks.push(chunk);
const { hash, password }=JSON.parse(Buffer.concat(chunks).toString("utf8"));
const directory=await mkdtemp(resolve(".sites-runtime/shared-check-"));
const app=await makeApp({dataDir:directory,accounts:{suelaine132:hash},secure:true});
const origin="https://ws132.test";
const response=await app.handle(new Request(origin+"/auth/login",{method:"POST",headers:{origin,"content-type":"application/x-www-form-urlencoded"},body:new URLSearchParams({user:"suelaine132",password})}));
assert.equal(response.status,303);
const cookie=response.headers.get("set-cookie").split(";")[0];
const me=await app.handle(new Request(origin+"/auth/me",{headers:{cookie}}));
assert.equal((await me.json()).name,"Wesley & Suelaine");
const state=await (await app.handle(new Request(origin+"/api/state",{headers:{cookie}}))).json();
assert.equal(state.settings.title,"W&S 132");
assert.equal(state.settings.person2,"Suelaine");
assert.equal(state.settings.entrySongId,"mirrors");
assert.equal(state.settings.albumSongId,"photograph");
app.sqlite.close();await rm(directory,{recursive:true,force:true});
console.log("PASS requested shared login, W&S 132 identity, Mirrors at entry and Photograph in the album.");
